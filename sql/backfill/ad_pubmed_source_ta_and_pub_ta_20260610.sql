-- 1) PMID set size used for backfill (re-create temp table if session ended)
--    For post-commit verification, use the derived filter directly:

SELECT
  COUNT(DISTINCT p.pubmed_id) AS ad_pubmed_pmids_in_scope,
  COUNT(DISTINCT p.id) FILTER (
    WHERE p.source_therapeutic_area_id = '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid
  ) AS pubs_with_source_ta_set,
  COUNT(DISTINCT p.id) FILTER (
    WHERE p.source_therapeutic_area_id IS NULL
  ) AS pubs_still_null_source_ta,
  COUNT(DISTINCT pta.publication_id) AS pubs_with_pub_ta_join
FROM publications_v2 p
JOIN publication_authors_v2 pa ON pa.publication_id = p.id
JOIN hcp_therapeutic_areas_v2 hta
  ON hta.hcp_id = pa.hcp_id
 AND hta.therapeutic_area_id = '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid
LEFT JOIN publication_therapeutic_areas_v2 pta
  ON pta.publication_id = p.id
 AND pta.therapeutic_area_id = '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid
WHERE p.pubmed_id IS NOT NULL
  AND p.source = 'pubmed';

