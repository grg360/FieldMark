BEGIN;

-- ----------------------------------------------------------------------------
-- Step 0: Build ad_pubmed_pmids temp table
-- ----------------------------------------------------------------------------

CREATE TEMP TABLE ad_pubmed_pmids (
  pubmed_id text PRIMARY KEY
);

-- METHOD A (recommended): uncomment after populating from checkpoint.
-- Paste INSERT rows generated by the PowerShell snippet at the bottom, e.g.:
--   INSERT INTO ad_pubmed_pmids (pubmed_id) VALUES
