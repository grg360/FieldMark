-- METHOD B (fallback): derived PMID set from tonight's ingest footprint.
-- Comment out if using Method A.
INSERT INTO ad_pubmed_pmids (pubmed_id)
SELECT DISTINCT p.pubmed_id
FROM publications_v2 p
JOIN publication_authors_v2 pa ON pa.publication_id = p.id
JOIN hcp_therapeutic_areas_v2 hta
  ON hta.hcp_id = pa.hcp_id
 AND hta.therapeutic_area_id = '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid
WHERE p.pubmed_id IS NOT NULL
  AND p.source = 'pubmed'
  AND p.source_therapeutic_area_id IS NULL
ON CONFLICT (pubmed_id) DO NOTHING;

-- Sanity check before mutating
SELECT COUNT(*) AS ad_pmid_count FROM ad_pubmed_pmids;

-- ----------------------------------------------------------------------------
-- Operation 1: Backfill source_therapeutic_area_id on publications_v2
-- ----------------------------------------------------------------------------

UPDATE publications_v2 p
SET source_therapeutic_area_id = '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid
FROM ad_pubmed_pmids a
WHERE p.pubmed_id = a.pubmed_id
  AND p.source_therapeutic_area_id IS NULL;

-- ----------------------------------------------------------------------------
-- Operation 2: Insert publication_therapeutic_areas_v2 join rows
-- ----------------------------------------------------------------------------

INSERT INTO publication_therapeutic_areas_v2 (
  publication_id,
  therapeutic_area_id,
  source
)
SELECT
  p.id,
  '9e4139d2-e062-4a58-8728-cdabb2d7dca1'::uuid,
  'pubmed'
FROM publications_v2 p
JOIN ad_pubmed_pmids a ON a.pubmed_id = p.pubmed_id
ON CONFLICT (publication_id, therapeutic_area_id) DO NOTHING;

COMMIT;

